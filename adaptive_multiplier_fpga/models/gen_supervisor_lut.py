#!/usr/bin/env python3
"""
gen_supervisor_lut.py

Generates rtl/supervisor_lut.vh: the offline error model error(width) that
the mode-11 supervisor uses at runtime.

    LUT_NMED[w] = round(NMED(w) * NMED_SCALE)       (NMED_SCALE = 1e6)

NMED(w) is the exhaustive population NMED of approx_mult at truncation
width w (all 2^N x 2^N operand pairs, uniform-operand assumption). It is
computed by the independent golden model (models/golden_model.py), or read
from the RTL's own results/error_vs_width.csv with --from-csv.

The .vh contains ONE constant function, lut_nmed(w). It is only ever called
at elaboration time (to build localparams / constant tables), so it costs
no hardware: every reciprocal and every drift threshold the supervisor
needs is folded into constants by the synthesizer. No runtime divider.

A pre-generated rtl/supervisor_lut.vh for N=8 is shipped in the zip, so
Python is NOT required to simulate. Re-run this only if you change N or
the approximation scheme.

Usage:
    python models/gen_supervisor_lut.py                       (golden model, N=8)
    python models/gen_supervisor_lut.py --from-csv results/error_vs_width.csv
"""
import argparse
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from golden_model import characterize  # noqa: E402

NMED_SCALE = 1_000_000


def monte_carlo_nmed(n, samples, seed=1):
    """Sampled NMED(width) for large N, same scheme as approx_mult.v."""
    import numpy as np
    rng = np.random.default_rng(seed)
    a = rng.integers(0, 1 << n, samples, dtype=np.uint64)
    b = rng.integers(0, 1 << n, samples, dtype=np.uint64)
    exact = (a * b).astype(np.float64)
    maxprod = float(((1 << n) - 1) ** 2)
    out = []
    for w in range(2 * n):
        mask = np.uint64(~((1 << w) - 1) & ((1 << (2 * n)) - 1))
        acc = np.zeros(samples, dtype=np.uint64)
        for i in range(n):
            bit = (b >> np.uint64(i)) & np.uint64(1)
            acc += ((a << np.uint64(i)) & mask) * bit
        if w > 0:
            acc += np.uint64(1 << (w - 1))
        out.append(float(np.mean(np.abs(exact - acc.astype(np.float64)))) / maxprod)
        print(f"width={w:2d}  NMED={out[-1]:.10f}  (sampled, {samples} pairs)")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=8)
    ap.add_argument("--from-csv", type=str, default=None,
                    help="use RTL-produced error_vs_width.csv instead of golden model")
    ap.add_argument("--out", type=str, default="rtl/supervisor_lut.vh")
    ap.add_argument("--samples", type=int, default=0,
                    help="Monte-Carlo characterization with this many random pairs "
                         "(needs numpy). Use for N > 8, where exhaustive is infeasible.")
    args = ap.parse_args()

    if args.samples:
        nmed = monte_carlo_nmed(args.n, args.samples)
    elif args.from_csv:
        with open(args.from_csv) as f:
            rows = {int(r["width"]): float(r["nmed"]) for r in csv.DictReader(f)}
        nmed = [rows[w] for w in range(2 * args.n)]
    else:
        nmed = [r["nmed"] for r in characterize(args.n)]

    lut = [int(round(v * NMED_SCALE)) for v in nmed]
    # width>0 entries must be >=1 so elaboration-time reciprocals are defined
    lut = [lut[0]] + [max(1, v) for v in lut[1:]]

    lines = []
    lines.append("// supervisor_lut.vh -- GENERATED by models/gen_supervisor_lut.py, do not hand-edit")
    lines.append(f"// N = {args.n}, NMED_SCALE = {NMED_SCALE}")
    how = (f"Monte-Carlo, {args.samples} random uniform pairs (seed 1)" if args.samples
           else "exhaustive, all uniform operand pairs")
    lines.append(f"// lut_nmed(w) = round(NMED(w) * NMED_SCALE), NMED of approx_mult: {how}")
    lines.append("// Only called at elaboration time -> zero hardware cost.")
    lines.append("/* verilator lint_off UNUSEDPARAM */")
    lines.append(f"localparam integer LUT_N = {args.n};   // N this table was generated for")
    lines.append("/* verilator lint_on UNUSEDPARAM */")
    lines.append("function integer lut_nmed;")
    lines.append("    input integer w;")
    lines.append("    begin")
    lines.append("        case (w)")
    for w, v in enumerate(lut):
        lines.append(f"            {w:2d}: lut_nmed = {v:7d};   // NMED = {nmed[w]:.8f}")
    lines.append(f"            default: lut_nmed = {lut[-1]};")
    lines.append("        endcase")
    lines.append("    end")
    lines.append("endfunction")

    with open(args.out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
